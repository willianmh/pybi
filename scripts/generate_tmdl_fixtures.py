def _roundtrip() -> tuple[SemanticModelDefinition, SemanticModelDefinition]:
    sm = _load()
    written = TMDLPartsWriter().write(sm)
    sm2 = SemanticModelDefinition(**TMDLPartsLoader(written).load())
    return sm, sm2


