# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------


def main() -> None:
    if not SAMPLES_ROOT.exists():
        print(
            f"ERROR: {SAMPLES_ROOT} not found.\n"
            "Clone https://github.com/willianmh/pbi-samples next to this repo."
        )
        sys.exit(1)

    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    init_file = OUTPUT_DIR / "__init__.py"
    if not init_file.exists():
        init_file.write_text("")

    samples = discover_samples(SAMPLES_ROOT)
    if not samples:
        print(f"ERROR: No *.SemanticModel directories found under {SAMPLES_ROOT}")
        sys.exit(1)

    print(f"Found {len(samples)} sample(s). Generating test files into {OUTPUT_DIR}/")

    for slug, sample_path in samples:
        print(f"  {slug}: {sample_path.name} ... ", end="", flush=True)
        try:
            tmdl_files = extract_tmdl_files(sample_path)
            meta = compute_metadata(tmdl_files)
            content = render_test_file(slug, sample_path, tmdl_files, meta)
            out_path = OUTPUT_DIR / f"test_{slug}_roundtrip.py"
            out_path.write_text(content, encoding="utf-8")
            print(
                f"OK ({meta['table_count']} tables, "
                f"{meta['relationship_count']} rels, "
                f"{len(tmdl_files)} tmdl files)"
            )
        except Exception as exc:
            print(f"FAILED: {exc}")
            raise

    print("Done.")


if __name__ == "__main__":
    main()
