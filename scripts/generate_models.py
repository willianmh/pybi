# Regex patterns for parsing generated Python code
_CLASS_DEF_PATTERN = re.compile(r"^class\s+(\w+)\s*\(", re.MULTILINE)
_NUMBERED_VARIANT_PATTERN = re.compile(r"^(\w+?)(\d+)$")


def extract_class_names(python_source: str) -> list[str]:
    """Extract all class names defined in a Python source string.

    Args:
        python_source: Complete Python source text.

    Returns:
        List of class names in declaration order.
    """
    return _CLASS_DEF_PATTERN.findall(python_source)


def extract_class_signatures(python_source: str) -> dict[str, str]:
    """Extract deterministic structural signatures for each class block.

    The signature intentionally ignores class *name* and whitespace so
    identical classes generated in different schemas can be safely
    deduplicated, while similarly named classes with different structure are
    kept local.

    Normalisation steps:
        1. Replace the class name in the header with ``__CLASS__``.
        2. Strip comments (``# …``).
        3. Collapse all whitespace to a single space.
        4. SHA-1 hash the result.

    Args:
        python_source: Complete Python source text.

    Returns:
        Dict mapping class name → hex SHA-1 digest of the normalised body.
    """
    signatures: dict[str, str] = {}
    class_names = extract_class_names(python_source)

    for class_name in class_names:
        block = find_class_block(python_source, class_name)
        if not block:
            continue
        start, end = block
        class_text = python_source[start:end]

        # Normalize the header to avoid name-specific hash differences.
        normalized = re.sub(
            rf"^class\s+{re.escape(class_name)}\s*\(",
            "class __CLASS__(",
            class_text,
            count=1,
            flags=re.MULTILINE,
        )
        # Remove comments and collapse whitespace for stable hashing.
        normalized = re.sub(r"#.*$", "", normalized, flags=re.MULTILINE)
        normalized = re.sub(r"\s+", " ", normalized).strip()

        signatures[class_name] = hashlib.sha1(normalized.encode("utf-8")).hexdigest()

    return signatures


def find_class_block(source: str, class_name: str) -> tuple[int, int] | None:
    """Find the start and end character positions of a class definition block.

    The algorithm works in two phases:

    **Phase 1: Header**: Starting from the ``class Name(`` match, track
    parenthesis depth to find the closing ``):``.  Strings and comments
    inside the header are skipped to avoid miscounting brackets.

    **Phase 2: Body**: Walk subsequent lines.  Any indented or blank line
    belongs to the body.  The first non-indented, non-empty line marks the
    start of the next top-level block.

    Handles multi-line class headers like::

        class Foo(
            RootModel[Type1 | Type2]
        ):
            root: ...

    Args:
        source: Complete Python source text.
        class_name: Exact class name to locate.

    Returns:
        ``(start, end)`` character offsets, or ``None`` if not found.

    Note:
        The string/comment skipper inside Phase 1 does not handle escaped
        quotes (``\\\"``) or raw strings.  This is acceptable for
        machine-generated code.
    """
    pattern = re.compile(
        rf"^class\s+{re.escape(class_name)}\s*\(",
        re.MULTILINE,
    )
    match = pattern.search(source)
    if not match:
        return None

    start = match.start()

    # Phase 1: Find the end of the class HEADER by tracking parenthesis depth.
    # The header starts at "class Name(" and ends when we find the matching ")"
    # followed by ":".
    pos = match.end()  # position right after the opening "("
    paren_depth = 1
    header_end = None

    while pos < len(source) and paren_depth > 0:
        ch = source[pos]
        if ch == "(":
            paren_depth += 1
        elif ch == ")":
            paren_depth -= 1
            if paren_depth == 0:
                # Find the ":" after the closing ")"
                rest = source[pos : pos + 20]
                colon_offset = rest.find(":")
                if colon_offset >= 0:
                    colon_pos = pos + colon_offset + 1
                    # Advance to end of line
                    newline = source.find("\n", colon_pos)
                    header_end = (newline + 1) if newline >= 0 else len(source)
                else:
                    header_end = pos + 1
                break
        elif ch == "#":
            # Skip to end of line (comment)
            newline = source.find("\n", pos)
            pos = newline if newline >= 0 else len(source)
            continue
        elif ch in ('"', "'"):
            # Skip string literals
            quote = source[pos : pos + 3]
            if quote in ('"""', "'''"):
                end_q = source.find(quote, pos + 3)
                pos = (end_q + 3) if end_q >= 0 else len(source)
                continue
            else:
                end_q = source.find(ch, pos + 1)
                pos = (end_q + 1) if end_q >= 0 else len(source)
                continue
        pos += 1

    if header_end is None:
        # Fallback: assume single-line header
        newline = source.find("\n", start)
        header_end = (newline + 1) if newline >= 0 else len(source)

    # Phase 2: Find the end of the class BODY.
    # The body consists of all indented lines (and blank lines) following the header.
    body_end = header_end
    remaining = source[header_end:]

    for line in remaining.split("\n"):
        stripped = line.strip()
        if stripped == "":
            body_end += len(line) + 1
            continue

        # A non-indented, non-empty line marks the start of the next block
        if line and not line[0].isspace():
            break

        body_end += len(line) + 1

    return start, body_end


def identify_numbered_variants(class_names: list[str]) -> dict[str, list[str]]:
    """Identify numbered class variants like ``QueryExpressionContainer1``-``47``.

    A class is considered a numbered variant if its name matches
    ``<BaseName><Digit(s)>`` (see ``_NUMBERED_VARIANT_PATTERN``).  Only
    groups with **2 or more** variants are returned: a single ``Foo1``
    without ``Foo2`` is not treated as a variant group.

    Args:
        class_names: List of class names from :func:`extract_class_names`.

    Returns:
        Dict mapping base name → sorted list of numbered variant names.
    """
    variants: dict[str, list[str]] = defaultdict(list)
    base_classes = set(class_names)

    for name in class_names:
        m = _NUMBERED_VARIANT_PATTERN.match(name)
        if m:
            base_name = m.group(1)
            # Only group as variants if:
            # 1. There are multiple numbered versions
            # 2. The base name also exists as a class OR there are >1 numbered versions
            variants[base_name].append(name)

    # Filter: only keep groups with 2+ variants
    return {k: sorted(v) for k, v in variants.items() if len(v) >= 2}


def _check_rootmodel_self_reference(
    source: str, base_name: str, variants: list[str]
) -> bool:
    """Check if merging variants would create a self-referential RootModel.

    Example:
        class VisualContainer(RootModel[VisualContainer1 | VisualContainer2]):
            root: VisualContainer1 | VisualContainer2

    If we merge VisualContainer1 and VisualContainer2 into VisualContainer,
    we'd get:
        class VisualContainer(RootModel[VisualContainer]):  # Self-reference!
            root: VisualContainer

    This function detects such cases by looking for a class named `base_name`
    that inherits from RootModel and references the variants.
    """
    # Look for a RootModel class with the base name that references the variants
    rootmodel_pattern = re.compile(
        rf"class\s+{re.escape(base_name)}\s*\(\s*RootModel\s*\[",
        re.MULTILINE,
    )
    match = rootmodel_pattern.search(source)
    if not match:
        return False

    # Found a RootModel class - check if it references the variants
    # Get the content after the match to find the type parameter
    start = match.end()
    bracket_depth = 1
    pos = start
    while pos < len(source) and bracket_depth > 0:
        if source[pos] == "[":
            bracket_depth += 1
        elif source[pos] == "]":
            bracket_depth -= 1
        pos += 1

    type_param = source[start : pos - 1]

    # Check if the type parameter contains any of the variants
    for variant in variants:
        if re.search(rf"\b{re.escape(variant)}\b", type_param):
            return True

    return False


def deduplicate_against_registry(
    source: str,
    schema_info: SchemaInfo,
    registry: ClassRegistry,
    schemas: dict[str, SchemaInfo],
) -> str:
    """Remove duplicate classes and replace with imports from the original schema.

    For each class defined in *source*, check if the :class:`ClassRegistry`
    already has it registered from a different schema.  If so: and if the
    structural signatures match (see :meth:`ClassRegistry.can_substitute`):
    the local class definition is removed and replaced with an import from
    the origin schema's module.

    Hand-crafted classes are imported via a wildcard import from
    ``expressions``; auto-generated classes get explicit ``from …
    import …`` statements built by :func:`_build_relative_import`.

    Args:
        source: Post-processed Python source text for the current schema.
        schema_info: The schema currently being processed.
        registry: Global class registry populated by previously generated
            schemas.
        schemas: Full schema dict (needed to resolve origin import paths).

    Returns:
        The source with duplicate class definitions removed and import
        statements added.

    Note:
        Class blocks are removed one at a time, mutating the source string
        between removals.  See "Known Issues" in the module docstring.
    """
    class_names = extract_class_names(source)
    class_signatures = extract_class_signatures(source)
    duplicates: dict[str, ClassRecord] = {}

    for cls_name in class_names:
        if registry.is_duplicate(cls_name, schema_info.key):
            origin = registry.get_origin(cls_name)
            if origin:
                current_sig = class_signatures.get(cls_name)
                if registry.can_substitute(cls_name, current_sig):
                    duplicates[cls_name] = origin
                else:
                    log.warning(
                        "  Keeping local class '%s' (signature mismatch with %s)",
                        cls_name,
                        origin.schema_key,
                    )

    if not duplicates:
        return source

    log.info("  Found %d duplicate classes to replace with imports", len(duplicates))

    # Group duplicates by origin module for clean import statements
    imports_by_module: dict[str, list[str]] = defaultdict(list)
    handcrafted_classes: list[str] = []

    for cls_name, record in duplicates.items():
        # Check if this is a hand-crafted class
        if cls_name in HANDCRAFTED_CLASSES:
            handcrafted_classes.append(cls_name)
            continue

        # Build relative import path for auto-generated classes
        origin_schema = schemas.get(record.schema_key)
        if origin_schema:
            # Calculate relative import from current schema's module to origin
            rel_import = _build_relative_import(schema_info, origin_schema)
            imports_by_module[rel_import].append(cls_name)

    # Remove duplicate class definitions from source
    for cls_name in duplicates:
        block = find_class_block(source, cls_name)
        if block:
            start, end = block
            source = source[:start] + source[end:]

    # Build import statements
    import_lines: list[str] = []

    # Add import for hand-crafted classes (explicit names, not wildcard)
    if handcrafted_classes:
        classes_str = ", ".join(sorted(handcrafted_classes))
        import_lines.append(f"from ...semanticquery.expressions import {classes_str}")
        log.info(
            "    Added hand-crafted import for %d classes", len(handcrafted_classes)
        )

    # Add imports for auto-generated classes from other schemas
    for module_path, class_list in sorted(imports_by_module.items()):
        classes_str = ", ".join(sorted(class_list))
        import_lines.append(f"from {module_path} import {classes_str}")

    if import_lines:
        source = _insert_imports(source, import_lines)

    return source


def _extract_imported_names(source: str) -> set[str]:
    """Extract class/symbol names that are imported (not locally defined).

    Parses ``from … import …`` statements via regex.  Handles comma-separated
    names and ``as`` aliases (returns the alias).  Does **not** handle
    wildcard imports: those are checked separately via ``HANDCRAFTED_CLASSES``.

    Args:
        source: Python source text.

    Returns:
        Set of imported symbol names.
    """
    imported: set[str] = set()
    for m in re.finditer(r"^from\s+\S+\s+import\s+(.+)$", source, re.MULTILINE):
        names = m.group(1)
        for name in names.split(","):
            name = name.strip().split(" as ")[-1].strip()
            if name and name.isidentifier():
                imported.add(name)
    return imported


def _remove_unused_imports(source: str) -> str:
    """Remove imported names that are not referenced in the rest of the file.

    After deduplication replaces local class definitions with imports, some
    of those imported names may not actually be used anywhere in the file
    (e.g., the class was defined but never referenced as a field type).
    This function removes those unused names from import statements.

    Wildcard imports (``from … import *``) are left untouched.

    Args:
        source: Python source text.

    Returns:
        The source with unused import names removed.
    """
    lines = source.split("\n")
    import_pattern = re.compile(r"^from\s+(\S+)\s+import\s+(.+)$")
    output_lines: list[str] = []

    for line in lines:
        m = import_pattern.match(line)
        if not m or "*" in m.group(2):
            output_lines.append(line)
            continue

        module = m.group(1)
        raw_names = [n.strip() for n in m.group(2).split(",") if n.strip()]

        # Check each name: is it referenced outside of import lines?
        # Build a version of source without any import lines to search in
        used_names: list[str] = []
        for name in raw_names:
            # Get the actual name (handle "X as Y" aliases)
            local_name = name.split(" as ")[-1].strip()
            # Check if the name appears anywhere in the file outside this import
            # Use word-boundary search in non-import lines
            pattern = re.compile(rf"\b{re.escape(local_name)}\b")
            found = False
            for other_line in lines:
                if other_line == line:
                    continue
                # Skip other import lines when checking for usage
                if import_pattern.match(other_line):
                    continue
                if pattern.search(other_line):
                    found = True
                    break
            if found:
                used_names.append(name)

        if used_names:
            names_str = ", ".join(used_names)
            output_lines.append(f"from {module} import {names_str}")
        # else: drop the entire import line

    return "\n".join(output_lines)


def _remove_stale_rebuild_calls(source: str) -> str:
    """Remove ``.model_rebuild()`` calls for classes not defined in the file.

    After deduplication removes class definitions (replacing them with imports),
    the corresponding ``ClassName.model_rebuild()`` calls become stale: they
    are unnecessary for imported classes.  This function removes them.

    Args:
        source: Python source text.

    Returns:
        The source with stale ``.model_rebuild()`` calls removed.
    """
    defined_classes = set(extract_class_names(source))
    lines = source.split("\n")
    output_lines: list[str] = []

    rebuild_pattern = re.compile(r"^(\w+)\.model_rebuild\(\)$")

    for line in lines:
        m = rebuild_pattern.match(line.strip())
        if m:
            class_name = m.group(1)
            if class_name not in defined_classes:
                continue  # Skip rebuild for non-local class
        output_lines.append(line)

    return "\n".join(output_lines)


def merge_numbered_variants(source: str) -> str:
    """Merge numbered class variants (e.g., ``Foo1``-``Foo47``) into a single base class.

    When ``datamodel-codegen`` encounters a schema with *N* optional fields and
    an "exactly one required" constraint, it generates *N* separate classes,
    each making a different field required.  This function collapses them:

    1. Identify numbered variant groups via :func:`identify_numbered_variants`.
    2. If the base class already exists (defined locally or imported), remove
       the variants and keep the base.
    3. If the base class does **not** exist, promote the first variant to act
       as the base via :func:`_promote_variant_to_base` (making all its
       required fields optional).
    4. A special case handles ``RootModel`` wrappers that would become
       self-referential after the merge: the wrapper is removed and the
       first variant is promoted instead.
    5. Replace **all** references to variant names with the base name.
    6. Clean up resulting duplicate union members, list items, and
       ``model_rebuild()`` calls.

    Args:
        source: Python source text (after deduplication).

    Returns:
        The source with all numbered variant groups collapsed.

    Note:
        The global ``re.sub`` in step 5 replaces variant names everywhere in
        the file, including inside string literals and ``description=`` Field
        arguments.  See "Known Issues" in the module docstring.
    """
    class_names = extract_class_names(source)
    variant_groups = identify_numbered_variants(class_names)

    if not variant_groups:
        return source

    # Also consider imported classes as "available" - this handles the case where
    # the base class was already generated in a dependency schema and imported.
    imported_names = _extract_imported_names(source)

    # Check for wildcard imports from expressions which imports all hand-crafted classes
    has_handcrafted_import = "from ...semanticquery.expressions import *" in source

    # Combine available names: local classes + imported names + hand-crafted (if imported)
    available_names = set(class_names) | imported_names
    if has_handcrafted_import:
        available_names |= HANDCRAFTED_CLASSES

    for base_name, variants in variant_groups.items():
        # Check if merging would create a self-referential RootModel
        # e.g., class VisualContainer(RootModel[VisualContainer1|VisualContainer2])
        # would become class VisualContainer(RootModel[VisualContainer])
        would_create_self_reference = _check_rootmodel_self_reference(
            source, base_name, variants
        )

        if would_create_self_reference:
            log.info(
                "  Merging %d numbered variants of '%s' with RootModel collapse (%s...%s)",
                len(variants),
                base_name,
                variants[0],
                variants[-1],
            )
            # Remove the RootModel wrapper class first
            rootmodel_block = find_class_block(source, base_name)
            if rootmodel_block:
                start, end = rootmodel_block
                source = source[:start] + source[end:]

            # Promote the first variant to the base name, making all fields optional
            source = _promote_variant_to_base(source, base_name, variants)
        else:
            log.info(
                "  Merging %d numbered variants of '%s' (%s...%s)",
                len(variants),
                base_name,
                variants[0],
                variants[-1],
            )

            base_available = base_name in available_names

            if base_available:
                # Base class exists (defined locally or imported) - just remove variants
                for variant in variants:
                    block = find_class_block(source, variant)
                    if block:
                        start, end = block
                        source = source[:start] + source[end:]
            else:
                # Base class not available - promote first variant to be the base class
                source = _promote_variant_to_base(source, base_name, variants)

        # Replace ALL references to numbered variants with the base class name
        for variant in variants:
            source = re.sub(
                rf"\b{re.escape(variant)}\b",
                base_name,
                source,
            )

    # Clean up: remove duplicate union members that result from the renaming
    source = _deduplicate_union_members(source)

    # Clean up: remove duplicate items in lists
    source = _deduplicate_list_items(source)

    # Clean up: remove duplicate model_rebuild() calls
    source = _deduplicate_rebuild_calls(source)

    # Remove any resulting blank lines clusters (more than 2 consecutive)
    source = re.sub(r"\n{4,}", "\n\n\n", source)

    return source


def _make_fields_optional(class_text: str) -> str:
    """Make all required fields in a class definition optional.

    Handles multi-line type annotations (``Literal[...]``, ``constr(…)``,
    ``Field(…)``) by tracking bracket depth to find where each field
    definition ends before processing it.

    For each required field (no ``None`` in type, no ``None`` default):

    1. Add ``| None`` after the type annotation.
    2. Change ``Field(…)`` to ``Field(None, …)`` or add ``= None`` if there
       is no ``Field()`` call.

    Args:
        class_text: The text of a single class definition (header + body).

    Returns:
        The class text with all required fields converted to optional.

    Note:
        The "already optional" check uses ``"None" in full_field`` which is a
        substring match.  This could mis-fire on identifiers that contain
        "None" as a substring (e.g., ``isNoneValue``).
    """
    lines = class_text.split("\n")
    result_lines: list[str] = []

    # Skip lines that are not field definitions (class header, model_config, etc.)
    # Field definitions start with: <indent><identifier>: <type>
    _FIELD_START = re.compile(r"^([ \t]+)(\w+):\s*(.*)$")
    # Lines that are NOT field starts (class def, model_config, decorators, etc.)
    _SKIP_PATTERNS = re.compile(r"^\s*(class\s|model_config\s*=|#|\)|extra\s*=|@|\s*$)")

    i = 0
    while i < len(lines):
        line = lines[i]
        m = _FIELD_START.match(line)

        # Skip non-field lines
        if not m or _SKIP_PATTERNS.match(line):
            result_lines.append(line)
            i += 1
            continue

        # Found a field definition start. Collect the full definition
        # (may span multiple lines due to multi-line Field() or Literal[])
        field_lines = [line]
        # Track bracket depth to find where this field definition ends
        depth = 0
        for ch in line:
            if ch in "([":
                depth += 1
            elif ch in ")]":
                depth -= 1

        j = i + 1
        while depth > 0 and j < len(lines):
            field_lines.append(lines[j])
            for ch in lines[j]:
                if ch in "([":
                    depth += 1
                elif ch in ")]":
                    depth -= 1
            j += 1

        full_field = "\n".join(field_lines)

        # Check if already optional
        indent = m.group(1)
        fname = m.group(2)
        type_and_rest = m.group(3)

        if "None" in full_field or "Optional" in full_field:
            # Already optional - keep as-is
            result_lines.extend(field_lines)
            i = j
            continue

        # Find the type annotation before any = or Field(
        # The type is everything between "field_name: " and " = " or end of first line
        # For multi-line types, we need to find where the type ends
        if "= Field(" in full_field:
            # Type is before "= Field("
            field_idx = full_field.index("= Field(")
            # Find the colon position (after field name)
            colon_pos = full_field.index(":", len(indent) + len(fname))
            type_str = full_field[colon_pos + 1 : field_idx].strip()

            # Add | None to type and change Field(...) to Field(None, ...)
            rest = full_field[field_idx:].replace("= Field(", "= Field(None, ", 1)
            # Remove the "..." sentinel (may be on separate line with whitespace)
            rest = re.sub(r"Field\(None,\s*\.\.\.\s*,", "Field(None,", rest)
            rest = re.sub(r"Field\(None,\s*\.\.\.\s*\)", "Field(None)", rest)
            new_field = full_field[: colon_pos + 1] + " " + type_str + " | None" + rest
            result_lines.extend(new_field.split("\n"))
        elif "=" not in type_and_rest:
            # Simple type with no default: "field_name: SomeType"
            result_lines.append(
                f"{indent}{fname}: {type_and_rest.rstrip()} | None = None"
            )
            # Add any continuation lines (shouldn't happen for simple types)
            result_lines.extend(field_lines[1:])
        else:
            # Has some default but no Field() - rare case, just keep as-is
            result_lines.extend(field_lines)

        i = j

    return "\n".join(result_lines)


def _promote_variant_to_base(source: str, base_name: str, variants: list[str]) -> str:
    """Promote the first variant to act as the base class, then remove the rest.

    Instead of merging fields from all variants (which breaks on multi-line
    ``Field()`` definitions), we take the *entire* first variant class block,
    rename it to *base_name*, and make all its required fields optional via
    :func:`_make_fields_optional`.

    If the first variant's block cannot be found (e.g., already removed by a
    prior step), a fallback path simply removes all variant blocks.

    Args:
        source: Python source text.
        base_name: The desired class name (without trailing digits).
        variants: Sorted list of numbered variant names (e.g.,
            ``["Foo1", "Foo2", …]``).

    Returns:
        The source with the first variant renamed and the rest removed.
    """
    # Get the first variant's complete class block
    first_block = find_class_block(source, variants[0])
    if not first_block:
        # Fallback: just remove all variants
        for variant in variants:
            block = find_class_block(source, variant)
            if block:
                start, end = block
                source = source[:start] + source[end:]
        return source

    start, end = first_block
    class_text = source[start:end]

    # Rename the class
    class_text = re.sub(
        rf"class\s+{re.escape(variants[0])}\s*\(",
        f"class {base_name}(",
        class_text,
        count=1,
    )

    # Make required fields optional by processing complete field definitions.
    # A field definition starts with "    field_name: Type..." and may span
    # multiple lines (e.g., Literal['long-url'], constr(max_length=50),
    # or multi-line Field(...) calls).
    class_text = _make_fields_optional(class_text)

    # Replace the first variant block with the renamed/modified class
    source = source[:start] + class_text + source[end:]

    # Remove remaining variant class definitions (skip the first, already replaced)
    for variant in variants[1:]:
        block = find_class_block(source, variant)
        if block:
            s, e = block
            source = source[:s] + source[e:]

    return source


def _deduplicate_union_members(source: str) -> str:
    """Remove duplicate members in union type annotations.

    After variant renaming, unions like
    ``QueryExpressionContainer | QueryExpressionContainer | …`` need to be
    collapsed to a single ``QueryExpressionContainer``.

    Three passes are applied:

    1. **Parenthesised unions**: ``(A | B | A)`` → ``A | B``.
    2. **Simple inline unions** after ``:``: ``field: A | A`` → ``field: A``.
    3. **Unions inside ``list[…]``**: ``list[A | A]`` → ``list[A]``.

    Args:
        source: Python source text (after variant renaming).

    Returns:
        The source with duplicate union members removed.
    """

    def _dedup_union_str(union_str: str) -> str:
        """Deduplicate a union string, preserving order."""
        # Normalize whitespace - collapse multiple spaces/newlines
        normalized = re.sub(r"\s+", " ", union_str)
        # Split by | and deduplicate
        members = [m.strip() for m in normalized.split("|")]
        seen: set[str] = set()
        unique: list[str] = []
        for member in members:
            if member and member not in seen:
                seen.add(member)
                unique.append(member)
        return " | ".join(unique)

    # First pass: Handle multi-line union types in parentheses
    # Pattern: (Type1\n| Type2\n| Type3...) or (list[Type1\n| Type2...])
    def _process_paren_block(match: re.Match) -> str:
        content = match.group(1)
        # Check if this contains union operators
        if "|" not in content:
            return match.group(0)
        # Deduplicate the union
        deduped = _dedup_union_str(content)
        # If result is simple enough, remove parentheses
        if "\n" not in deduped and len(deduped) < 100:
            return deduped
        return f"({deduped})"

    # Match parenthesized type annotations that might span multiple lines
    source = re.sub(
        r"\(\s*([\w\[\], \n\t|]+)\s*\)",
        _process_paren_block,
        source,
        flags=re.DOTALL,
    )

    # Second pass: Handle single-line union types after ":"
    def _dedup_simple_union(match: re.Match) -> str:
        return _dedup_union_str(match.group(0))

    source = re.sub(
        r"(?<=:\s)[\w\[\], ]+(?:\s*\|\s*[\w\[\], ]+)+",
        _dedup_simple_union,
        source,
    )

    # Third pass: Handle union types inside list[] brackets (including multi-line)
    def _dedup_list_union(match: re.Match) -> str:
        content = match.group(1)
        if "|" not in content:
            return match.group(0)
        deduped = _dedup_union_str(content)
        return f"list[{deduped}]"

    # Match list[...] with potential multi-line union content
    source = re.sub(
        r"list\[([\w\[\], \n\t|]+)\]",
        _dedup_list_union,
        source,
        flags=re.DOTALL,
    )

    return source


def _deduplicate_list_items(source: str) -> str:
    """Remove duplicate items in list literals like ``[Type, Type, Type]`` → ``[Type]``.

    Args:
        source: Python source text.

    Returns:
        The source with duplicate list items collapsed.

    Note:
        The regex ``\\[([^\\[\\]]+)\\]`` matches **any** non-nested bracketed
        content, not just type annotations.  It could corrupt list
        comprehensions or string literals in arbitrary Python, but is safe
        for ``datamodel-codegen`` output.
    """

    def _dedup_list(match: re.Match) -> str:
        inner = match.group(1)
        items = [item.strip() for item in inner.split(",") if item.strip()]
        seen: set[str] = set()
        unique: list[str] = []
        for item in items:
            if item not in seen:
                seen.add(item)
                unique.append(item)
        return "[" + ", ".join(unique) + "]"

    source = re.sub(r"\[([^\[\]]+)\]", _dedup_list, source)
    return source


def _deduplicate_rebuild_calls(source: str) -> str:
    """Remove duplicate ``X.model_rebuild()`` calls.

    After variant renaming, multiple identical ``model_rebuild()`` calls may
    exist (one per original variant).  This keeps only the first occurrence
    of each.

    Args:
        source: Python source text.

    Returns:
        The source with duplicate ``model_rebuild()`` calls removed.
    """
    lines = source.split("\n")
    seen_rebuilds: set[str] = set()
    output_lines: list[str] = []

    for line in lines:
        stripped = line.strip()
        if stripped.endswith(".model_rebuild()"):
            if stripped in seen_rebuilds:
                continue  # Skip duplicate
            seen_rebuilds.add(stripped)
        output_lines.append(line)

    return "\n".join(output_lines)


def _build_relative_import(
    current_schema: SchemaInfo,
    origin_schema: SchemaInfo,
) -> str:
    """Build a Python relative import path from current schema to origin schema.

    Both modules live under ``src/pybi/report/models/{schema_name}/{version}/model.py``.
    The relative import goes up 2 levels (version → schema → models root) then
    down into the origin module.

    Example::

        filterconfiguration.v1_2_0.model → semanticquery.v1_3_0.model
        ⇒ "...semanticquery.v1_3_0.model"

    Args:
        current_schema: The schema whose ``model.py`` contains the import.
        origin_schema: The schema that originally defined the class.

    Returns:
        A relative import string like ``"...semanticquery.v1_3_0.model"``.

    Note:
        The three-dot prefix (``...``) is hardcoded and assumes both schemas
        are always at the same directory depth.
    """
    # We go up 2 levels from current: version_dir → schema_name → models root
    # Then down into origin: schema_name → version_dir → model
    return f"...{origin_schema.module_name}.{origin_schema.version_dir}.model"


def _insert_imports(source: str, import_lines: list[str]) -> str:
    """Insert import statements after the existing import block.

    Scans for the last ``from …`` / ``import …`` line (including
    ``from __future__``) and inserts the new imports immediately after it,
    separated by a comment banner.

    Args:
        source: Python source text.
        import_lines: List of import statements to insert (without newlines).

    Returns:
        The source with the new imports inserted.

    Note:
        The "last import line" heuristic does not distinguish top-level
        imports from imports inside class bodies or string literals.  Safe
        for ``datamodel-codegen`` output which has a flat structure.
    """
    lines = source.split("\n")
    last_import_idx = 0

    for i, line in enumerate(lines):
        stripped = line.strip()
        if stripped.startswith(("from ", "import ")) and not stripped.startswith(
            "from __future__"
        ):
            last_import_idx = i
        elif stripped.startswith("from __future__"):
            last_import_idx = i

    # Insert after the last import line
    insert_idx = last_import_idx + 1

    # Add a blank line before our imports for clarity
    import_block = ["", "# --- Imports from dependency schemas (auto-generated) ---"]
    import_block.extend(import_lines)
    import_block.append("")

    lines[insert_idx:insert_idx] = import_block
    return "\n".join(lines)


