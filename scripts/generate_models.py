def main() -> None:
    """CLI entry point.  Parses arguments and delegates to :func:`generate_all`.

    Exit codes:
        0: all schemas generated successfully.
        1: one or more schemas failed, or ``--schema-root`` does not exist.
    """
    parser = argparse.ArgumentParser(
        description="Generate Pydantic V2 models from Power BI JSON schemas.",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog=textwrap.dedent("""\
            Examples:
              python scripts/generate_models.py
              python scripts/generate_models.py --dry-run
              python scripts/generate_models.py --clean
              python scripts/generate_models.py --incremental
              python scripts/generate_models.py --schema-root /path/to/schemas
        """),
    )
    parser.add_argument(
        "--schema-root",
        type=Path,
        default=DEFAULT_SCHEMA_ROOT,
        help="Root directory containing the JSON schemas",
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Show what would be generated without actually generating",
    )
    parser.add_argument(
        "--clean",
        action="store_true",
        help="Remove existing generated files before regenerating",
    )
    parser.add_argument(
        "--incremental",
        action="store_true",
        help=(
            "Skip schemas whose model.py already exists. "
            "Existing schemas still populate the class registry so "
            "downstream deduplication works correctly."
        ),
    )
    parser.add_argument(
        "--verbose",
        "-v",
        action="store_true",
        help="Enable verbose/debug logging",
    )

    args = parser.parse_args()

    if args.verbose:
        logging.getLogger().setLevel(logging.DEBUG)

    if not args.schema_root.exists():
        log.error("Schema root not found: %s", args.schema_root)
        sys.exit(1)

    success = generate_all(
        schema_root=args.schema_root,
        targets=TARGET_SCHEMAS,
        dry_run=args.dry_run,
        clean=args.clean,
        incremental=args.incremental,
    )

    sys.exit(0 if success else 1)


if __name__ == "__main__":
    main()
