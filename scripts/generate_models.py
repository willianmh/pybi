def generate_all(
    schema_root: Path,
    targets: list[tuple[str, str, str]],
    dry_run: bool = False,
    clean: bool = False,
    incremental: bool = False,
) -> bool:
    """Main entry point: discover, generate, post-process, and organise.

    Orchestrates the full pipeline described in the module docstring.
    Each schema is processed sequentially in dependency order.  Failures
    are logged but do not abort the run: subsequent schemas continue.

    Args:
        schema_root: Root directory containing schema subdirectories.
        targets: List of ``(name, version, filename)`` tuples.
        dry_run: If ``True``, print the generation plan and exit.
        clean: If ``True``, remove existing output directories before
            regenerating.
        incremental: If ``True``, skip schemas whose ``model.py`` already
            exists.  Skipped schemas still populate the class registry so
            downstream deduplication works correctly.

    Returns:
        ``True`` if all schemas generated successfully, ``False`` if any
        failed.
    """

    log.info("=" * 70)
    log.info("Power BI Report Data Model Generation")
    log.info("=" * 70)
    log.info("Schema root : %s", schema_root)
    log.info("Output root : %s", OUTPUT_ROOT)
    log.info("")

    # Phase 1: Discover all schemas and dependencies
    log.info("[Phase 1] Discovering schemas and dependencies...")
    schemas = discover_schemas(targets, schema_root)
    log.info("  Found %d schemas (including transitive dependencies)", len(schemas))

    for key, info in schemas.items():
        deps = ", ".join(info.depends_on) if info.depends_on else "(none)"
        log.info("  %s → depends on: %s", key, deps)

    # Phase 2: Compute generation order
    log.info("")
    log.info("[Phase 2] Computing generation order (topological sort)...")
    ordered = topological_sort(schemas)
    log.info("  Generation order:")
    for i, s in enumerate(ordered, 1):
        log.info("    %d. %s (%s)", i, s.key, s.filename)

    if dry_run:
        log.info("")
        log.info("[DRY RUN] Would generate %d schemas. Exiting.", len(ordered))
        return True

    # Phase 3: Clean output if requested
    if clean:
        log.info("")
        log.info("[Phase 3] Cleaning output directory...")
        for s in ordered:
            if s.output_dir.exists():
                shutil.rmtree(s.output_dir)
                log.info("  Removed: %s", s.output_dir)

    if incremental and clean:
        log.warning(
            "--clean and --incremental were both set; --clean runs first so "
            "--incremental will have nothing to skip (full regeneration)."
        )

    # Phase 4: Generate models in dependency order
    log.info("")
    log.info("[Phase 4] Generating models...")
    registry = ClassRegistry()
    generated: list[SchemaInfo] = []
    skipped: list[SchemaInfo] = []
    failed: list[SchemaInfo] = []

    # Pre-register hand-crafted classes so downstream schemas will import them
    log.info("")
    log.info("  Pre-registering hand-crafted classes...")
    pre_register_handcrafted_classes(registry)

    for i, schema_info in enumerate(ordered, 1):
        log.info("")
        log.info(
            "[%d/%d] Generating %s v%s...",
            i,
            len(ordered),
            schema_info.name,
            schema_info.version,
        )

        # Incremental mode: skip schemas whose model.py already exists,
        # but still populate the registry from the existing file so that
        # downstream deduplication against this schema works correctly.
        if incremental and schema_info.output_file.exists():
            existing_source = schema_info.output_file.read_text(encoding="utf-8")
            existing_lines = existing_source.count("\n")
            log.info("  Skipping (already exists): %d lines", existing_lines)
            existing_classes = extract_class_names(existing_source)
            existing_signatures = extract_class_signatures(existing_source)
            for cls_name in existing_classes:
                registry.register(
                    cls_name,
                    schema_info.key,
                    schema_info.import_path,
                    signature=existing_signatures.get(cls_name),
                )
            create_init_files(schema_info)
            ensure_handcrafted_helper_files(schema_info)
            skipped.append(schema_info)
            continue

        # 4a: Run datamodel-codegen
        if not run_codegen(schema_info):
            log.error("  FAILED: Skipping post-processing for %s", schema_info.key)
            failed.append(schema_info)
            continue

        # Read generated source
        source = schema_info.output_file.read_text(encoding="utf-8")
        original_lines = source.count("\n")
        log.info("  Generated: %d lines", original_lines)

        # 4b: Extract class names and register them
        class_names_before_dedup = extract_class_names(source)

        # 4c: For semanticQuery, remove hand-crafted classes and use imports instead
        if schema_info.name == "semanticQuery":
            source = remove_handcrafted_classes(source, schema_info)

        # 4d: Deduplicate against previously generated schemas
        source = deduplicate_against_registry(source, schema_info, registry, schemas)

        # 4e: Merge numbered variants (QueryExpressionContainer1-47 → single class)
        # This is now mostly redundant for semanticQuery since we remove variants,
        # but still useful for other schemas and as a fallback
        source = merge_numbered_variants(source)

        # 4f: Normalise non-None defaults on Optional (| None) fields.
        # datamodel-codegen copies JSON Schema defaults verbatim; for models
        # serialised with exclude_none=True this causes spurious output.
        source = _fix_optional_field_defaults(source)

        # 4f½: Replace constr() with Annotated[str, StringConstraints(...)].
        source = _replace_constr_with_annotated(source)

        # 4g: Apply any schema-specific field type corrections (e.g. class-name
        # collisions that the generic dedup step cannot resolve automatically).
        source = _apply_post_generation_fixes(source, schema_info)

        # 4h: Remove .model_rebuild() for classes not defined in this file
        source = _remove_stale_rebuild_calls(source)

        # 4i: Remove unused imports left by deduplication/merging
        source = _remove_unused_imports(source)

        # 4j: Write the post-processed source
        schema_info.output_file.write_text(source, encoding="utf-8")
        final_lines = source.count("\n")

        if final_lines < original_lines:
            reduction = (1 - final_lines / original_lines) * 100
            log.info(
                "  Post-processed: %d → %d lines (%.1f%% reduction)",
                original_lines,
                final_lines,
                reduction,
            )
        else:
            log.info("  Post-processed: %d lines (no duplicates found)", final_lines)

        if final_lines > MAX_LINES_WARN:
            log.warning(
                "  ⚠ File has %d lines (>%d) - may need manual review",
                final_lines,
                MAX_LINES_WARN,
            )

        # 4i: Register all classes from this schema (after dedup)
        final_classes = extract_class_names(source)
        final_signatures = extract_class_signatures(source)
        for cls_name in final_classes:
            registry.register(
                cls_name,
                schema_info.key,
                schema_info.import_path,
                signature=final_signatures.get(cls_name),
            )

        log.info("  Registered %d classes from %s", len(final_classes), schema_info.key)

        # 4j: Create __init__.py files
        create_init_files(schema_info)
        ensure_handcrafted_helper_files(schema_info)

        generated.append(schema_info)

    # Phase 5: Create top-level init
    log.info("")
    log.info("[Phase 5] Creating package __init__.py files...")
    create_top_level_init(generated)

    # Phase 6: Summary
    log.info("")
    log.info("=" * 70)
    log.info("SUMMARY")
    log.info("=" * 70)
    log.info("Generated : %d schemas", len(generated))
    log.info("Skipped   : %d schemas", len(skipped))
    log.info("Failed    : %d schemas", len(failed))
    log.info("Registry  : %d unique classes", len(registry.all_classes))
    log.info("")

    for s in generated:
        lines = s.output_file.read_text(encoding="utf-8").count("\n")
        status = "⚠" if lines > MAX_LINES_WARN else "✓"
        log.info("  %s %s v%s → %d lines", status, s.name, s.version, lines)

    for s in skipped:
        lines = s.output_file.read_text(encoding="utf-8").count("\n")
        log.info("  ~ %s v%s → %d lines (skipped)", s.name, s.version, lines)

    if failed:
        log.error("")
        log.error("FAILED SCHEMAS:")
        for s in failed:
            log.error("  ✗ %s v%s", s.name, s.version)

    log.info("")
    log.info("Output directory: %s", OUTPUT_ROOT)
    log.info("")

    return len(failed) == 0


