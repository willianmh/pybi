"""Automation script for generating Pydantic V2 models from Power BI JSON schemas.

This script solves the key challenge with ``datamodel-codegen``: when schemas
reference other schemas via ``$ref``, the tool inlines all definitions, causing
massive class duplication (e.g., ``QueryExpressionContainer`` exploding into 47
numbered variants).

Usage::

    python scripts/generate_models.py
    python scripts/generate_models.py --dry-run
    python scripts/generate_models.py --schema-root /path/to/schemas
    python scripts/generate_models.py --clean

Dependencies:
    - ``datamodel-code-generator`` (pip install datamodel-code-generator)
    - Power BI JSON schemas in the directory pointed to by ``--schema-root``
      (default: ``DEFAULT_SCHEMA_ROOT``, currently a hardcoded absolute path).

Architecture / Pipeline Stages:
    The main entry point is :func:`generate_all`, which orchestrates the
    following phases:

    1. **Discovery**: :func:`discover_schemas` performs a BFS walk starting
       from ``TARGET_SCHEMAS``, parsing each JSON file for ``$ref`` links to
       discover transitive dependencies.  The result is a dict of
       :class:`SchemaInfo` objects.

    2. **Ordering**: :func:`topological_sort` (Kahn's algorithm) computes a
       generation order so that base schemas are generated before the schemas
       that depend on them.

    3. **Code generation**: :func:`run_codegen` shells out to
       ``datamodel-codegen`` for each schema (with retry logic).

    4. **Post-processing**: the generated Python source goes through several
       transforms applied in order:

       a. :func:`remove_handcrafted_classes`: strip classes that have
          hand-crafted implementations and add an import instead
          (``semanticQuery`` only).
       b. :func:`deduplicate_against_registry`: remove classes already
          generated by a dependency schema and replace with cross-module
          imports.  Uses :class:`ClassRegistry` with structural-signature
          matching for safety.
       c. :func:`merge_numbered_variants`: collapse numbered variants
          (e.g., ``Foo1``-``Foo47``) into a single ``Foo`` class.
       d. :func:`_fix_optional_field_defaults`: normalise ``Field(False, …)``
          to ``Field(None, …)`` on ``Optional`` fields.
       e. :func:`_apply_post_generation_fixes`: apply schema-specific
          field-type corrections from ``POST_GENERATION_FIELD_FIXES``.

    5. **Registration**: surviving classes are registered in the
       :class:`ClassRegistry` so later schemas can deduplicate against them.

    6. **Packaging**: :func:`create_init_files` and
       :func:`create_top_level_init` emit ``__init__.py`` files for the
       versioned module tree.

Key Design Decisions:
    - **First-wins registration**: :meth:`ClassRegistry.register` stores the
      first schema that defines a class.  All subsequent schemas that generate
      the same class (with a matching structural signature) replace the local
      definition with an import.
    - **Signature-based substitution**: To avoid silently replacing a class
      whose structure has diverged, the registry compares SHA-1 hashes of
      normalised class bodies.  Only exact structural matches are substituted.
    - **Hand-crafted override**: A curated set of classes
      (``HANDCRAFTED_CLASSES``) is pre-registered with a sentinel signature
      (``"__handcrafted__"``).  These are always substituted with a wildcard
      import from ``expressions``.
    - **Last-version-wins init files**: When multiple versions of the same
      schema are generated (e.g., ``semanticQuery/1.2.0`` and ``1.3.0``), the
      schema-level ``__init__.py`` is overwritten each time.  Only the last
      version processed ends up re-exported.  Because :func:`topological_sort`
      is stable and versions are listed in ascending order in
      ``TARGET_SCHEMAS``, the *latest* version wins.

Known Issues / Future Refactor Notes:
    1. **Sequential class removal is position-fragile**: Functions that remove
       class blocks one at a time (``deduplicate_against_registry``,
       ``remove_handcrafted_classes``, ``_promote_variant_to_base``) mutate the
       source string between removals.  This works only because
       ``find_class_block`` re-searches the modified string each iteration, but
       is O(n*m) and would break if two removals overlapped.  Collecting all
       blocks first and removing in reverse offset order would be safer.

    2. **``_deduplicate_list_items`` regex is over-broad**: The pattern
       ``\\[([^\\[\\]]+)\\]`` matches *any* square-bracketed content, not just
       type annotations.  It could theoretically corrupt list comprehensions or
       string literals.  Acceptable for machine-generated code, but should be
       constrained in a refactor.

    3. **Global ``re.sub`` for variant renaming**: In
       ``merge_numbered_variants``, variant names are replaced with a blanket
       ``\\b`` word-boundary regex that also matches inside string literals,
       comments, and ``description=`` Field arguments.

    4. **``_make_fields_optional`` substring check**: The guard
       ``"None" in full_field`` is a substring match and could mis-fire on
       identifiers that contain "None" (e.g., ``isNoneValue``).

    5. **``ModuleNotFoundError`` / ``ImportError`` classified as transient**:
       These are deterministic failures and retrying will not resolve them.

    6. **``_insert_imports`` fragile import detection**: The heuristic that
       finds "the last import line" does not distinguish top-level imports from
       imports inside class bodies or string literals.  Safe for
       ``datamodel-codegen`` output, but fragile for arbitrary Python.

    7. **``DEFAULT_SCHEMA_ROOT`` is a hardcoded absolute path**: Not portable.
       Other developers must always pass ``--schema-root``.
"""

