# Regex to find all "$ref": "..." values in a JSON file
_REF_PATTERN = re.compile(r'"\$ref"\s*:\s*"([^"]+)"')

# Regex to match external refs (not starting with #)
_EXTERNAL_REF_PATTERN = re.compile(
    r"^\.\./\.\./(?P<schema>[^/]+)/(?P<version>[^/]+)/(?P<file>[^#]+)"
)


def parse_external_refs(schema_path: Path) -> list[str]:
    """Extract all external ``$ref`` target strings from a JSON schema file.

    Uses a regex scan (not a JSON parser) so it works even on malformed JSON.
    Internal refs (starting with ``#``) are excluded.

    Args:
        schema_path: Absolute path to a ``.json`` schema file.

    Returns:
        List of raw ``$ref`` values that point to other schema files,
        e.g. ``["../../semanticQuery/1.3.0/schema.json#/definitions/Foo"]``.
    """
    content = schema_path.read_text(encoding="utf-8")
    refs = _REF_PATTERN.findall(content)
    return [r for r in refs if not r.startswith("#")]


def resolve_dependency_key(ref: str) -> tuple[str, str, str] | None:
    """Parse an external $ref into (schema_name, version, filename).

    Example: '../../semanticQuery/1.3.0/schema.json#/definitions/Foo'
    Returns: ('semanticQuery', '1.3.0', 'schema.json')
    """
    m = _EXTERNAL_REF_PATTERN.match(ref)
    if m:
        return m.group("schema"), m.group("version"), m.group("file")
    return None


def discover_schemas(
    targets: list[tuple[str, str, str]],
    schema_root: Path,
) -> dict[str, SchemaInfo]:
    """Discover all schemas (targets + transitive dependencies) via BFS.

    Starting from *targets*, each schema file is parsed for external ``$ref``
    links.  Any referenced schema not already visited is added to the queue,
    ensuring transitive dependencies are included automatically.

    Args:
        targets: List of ``(name, version, filename)`` tuples from
            ``TARGET_SCHEMAS``.
        schema_root: Root directory containing schema subdirectories.

    Returns:
        Dict mapping ``"name/version"`` keys to populated :class:`SchemaInfo`
        instances.  Missing schema files are logged as warnings and skipped.
    """
    schemas: dict[str, SchemaInfo] = {}
    queue: deque[tuple[str, str, str]] = deque(targets)
    visited: set[str] = set()

    while queue:
        name, version, filename = queue.popleft()
        key = f"{name}/{version}"
        if key in visited:
            continue
        visited.add(key)

        abs_path = schema_root / name / version / filename
        if not abs_path.exists():
            log.warning("Schema file not found: %s", abs_path)
            continue

        info = SchemaInfo(
            name=name, version=version, filename=filename, abs_path=abs_path
        )
        info.external_refs = parse_external_refs(abs_path)

        # Resolve each external ref to a dependency schema
        for ref in info.external_refs:
            dep = resolve_dependency_key(ref)
            if dep:
                dep_name, dep_version, dep_file = dep
                dep_key = f"{dep_name}/{dep_version}"
                info.depends_on.add(dep_key)

                # If this dependency isn't already queued/visited, add it
                if dep_key not in visited:
                    queue.append((dep_name, dep_version, dep_file))

        schemas[key] = info

    return schemas


def topological_sort(schemas: dict[str, SchemaInfo]) -> list[SchemaInfo]:
    """Return schemas in dependency order (base schemas first).

    Uses Kahn's algorithm (BFS from zero-in-degree nodes).  Raises
    ``RuntimeError`` if a cycle is detected: this indicates a bug in the
    schema repository or in :func:`discover_schemas`.

    Args:
        schemas: Dict of ``"name/version"`` → :class:`SchemaInfo` as returned
            by :func:`discover_schemas`.

    Returns:
        List of :class:`SchemaInfo` in a valid generation order.

    Raises:
        RuntimeError: If the dependency graph contains a cycle.
    """
    in_degree: dict[str, int] = {k: 0 for k in schemas}
    dependents: dict[str, list[str]] = defaultdict(list)

    for key, info in schemas.items():
        for dep_key in info.depends_on:
            if dep_key in schemas:
                in_degree[key] += 1
                dependents[dep_key].append(key)

    queue: deque[str] = deque(k for k, d in in_degree.items() if d == 0)
    order: list[SchemaInfo] = []

    while queue:
        key = queue.popleft()
        order.append(schemas[key])
        for dependent in dependents[key]:
            in_degree[dependent] -= 1
            if in_degree[dependent] == 0:
                queue.append(dependent)

    if len(order) != len(schemas):
        unresolved = set(schemas.keys()) - {s.key for s in order}
        log.error("Circular dependency detected! Unresolved: %s", unresolved)
        raise RuntimeError(f"Circular dependency among: {unresolved}")

    return order


