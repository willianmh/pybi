@dataclass
class ClassRecord:
    """A generated Python class and its origin schema."""

    class_name: str
    schema_key: str  # which schema generated it
    import_path: str  # Python import path
    signature: str | None = None  # structural fingerprint of class block


class ClassRegistry:
    """Tracks all generated classes to detect and resolve duplicates across schemas.

    The registry is the central data structure for cross-schema deduplication.
    As each schema is generated and post-processed, its surviving classes are
    registered here.  When a later schema generates a class with the same name,
    the registry is consulted to decide whether the duplicate can be safely
    replaced with an import (see :meth:`can_substitute`).

    Registration uses **first-wins** semantics: the first schema to register a
    class name owns it.  Subsequent calls to :meth:`register` with the same
    name are silently ignored.  Hand-crafted classes are pre-registered by
    :func:`pre_register_handcrafted_classes` before any code generation begins.
    """

    def __init__(self) -> None:
        self._classes: dict[str, ClassRecord] = {}

    def register(
        self,
        class_name: str,
        schema_key: str,
        import_path: str,
        signature: str | None = None,
    ) -> None:
        """Register a class as belonging to *schema_key*.

        Uses first-wins semantics: if *class_name* is already registered the
        call is a no-op.  The optional *signature* is a SHA-1 hash of the
        normalised class body, used by :meth:`can_substitute` to verify
        structural equivalence before cross-schema substitution.
        """
        if class_name not in self._classes:
            self._classes[class_name] = ClassRecord(
                class_name,
                schema_key,
                import_path,
                signature,
            )

    def is_duplicate(self, class_name: str, current_schema_key: str) -> bool:
        """Return True if this class name was already generated by a DIFFERENT schema."""
        rec = self._classes.get(class_name)
        return rec is not None and rec.schema_key != current_schema_key

    def get_origin(self, class_name: str) -> ClassRecord | None:
        return self._classes.get(class_name)

    def can_substitute(
        self,
        class_name: str,
        current_signature: str | None,
    ) -> bool:
        """Return whether cross-schema substitution is safe for this class.

        Rules:
        - Hand-crafted classes are always substitutable (explicitly pre-registered)
        - Auto-generated classes must have matching structural signatures
        - Missing signatures default to NOT substitutable (fail-safe)
        """
        rec = self._classes.get(class_name)
        if rec is None:
            return False

        if rec.signature == "__handcrafted__":
            return True

        if rec.signature is None or current_signature is None:
            return False

        return rec.signature == current_signature

    @property
    def all_classes(self) -> dict[str, ClassRecord]:
        return dict(self._classes)


