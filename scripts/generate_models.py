def create_top_level_init(schemas: list[SchemaInfo]) -> None:
    """Create the top-level ``models/__init__.py`` listing all generated schemas.

    The file contains commented-out imports for each schema/version pair
    (for reference) and an empty ``__all__`` list.

    If the file already exists and does **not** contain the ``"auto-generated"``
    marker, it is assumed to have custom content and is left untouched.

    Args:
        schemas: List of successfully generated :class:`SchemaInfo` instances.
    """
    lines = [
        '"""Power BI Report Data Models - auto-generated from JSON schemas.',
        "",
        "Do not edit manually. Regenerate with: python scripts/generate_models.py",
        '"""',
        "",
    ]

    all_exports: list[str] = []

    for schema_info in schemas:
        module = f".{schema_info.module_name}.{schema_info.version_dir}.model"
        lines.append(f"# {schema_info.name} v{schema_info.version}")
        lines.append(f"# from {module} import *  # noqa: F401")
        lines.append("")

    lines.append("")
    lines.append("__all__: list[str] = []  # Populate as needed")
    lines.append("")

    init_path = OUTPUT_ROOT / "__init__.py"
    # Don't overwrite if it already exists and has custom content
    if init_path.exists():
        existing = init_path.read_text(encoding="utf-8")
        if "auto-generated" not in existing:
            log.info("Skipping top-level __init__.py (has custom content)")
            return

    init_path.write_text("\n".join(lines), encoding="utf-8")


