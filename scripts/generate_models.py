@dataclass
class SchemaInfo:
    """Metadata for a single JSON schema to generate.

    Instances are created by :func:`discover_schemas` and carry both the
    input location (``abs_path``) and derived output paths (``output_dir``,
    ``output_file``).

    Attributes:
        name: Schema directory name, e.g. ``"semanticQuery"``.
        version: Semver string, e.g. ``"1.3.0"``.
        filename: JSON file inside the version directory, e.g.
            ``"schema.json"`` or ``"schema-embedded.json"``.
        abs_path: Resolved absolute path to the JSON file on disk.
        external_refs: Raw ``$ref`` target strings parsed from the schema
            (populated by :func:`parse_external_refs`).
        depends_on: Set of schema keys (``"name/version"``) that must be
            generated before this schema.

    Computed properties:
        key: ``"name/version"`` identifier used as dict key throughout.
        module_name: Python-safe directory name (``camelCase`` → lowercase).
        version_dir: ``"v2_3_0"``-style directory name.
        output_dir: Full path to the output directory under ``OUTPUT_ROOT``.
        output_file: Full path to the generated ``model.py``.
        import_path: Dot-separated import path relative to the models root.
    """

    name: str
    version: str
    filename: str
    abs_path: Path = field(default_factory=Path)

    external_refs: list[str] = field(default_factory=list)
    depends_on: set[str] = field(default_factory=set)

    @property
    def key(self) -> str:
        return f"{self.name}/{self.version}"

    @property
    def module_name(self) -> str:
        """Python-safe module name: camelCase → lowercase."""
        return self.name.lower()

    @property
    def version_dir(self) -> str:
        """Version as directory name: '2.3.0' → 'v2_3_0'."""
        return "v" + self.version.replace(".", "_")

    @property
    def output_dir(self) -> Path:
        return OUTPUT_ROOT / self.module_name / self.version_dir

    @property
    def output_file(self) -> Path:
        return self.output_dir / "model.py"

    @property
    def import_path(self) -> str:
        """Dot-separated import path relative to models root."""
        return f"{self.module_name}.{self.version_dir}.model"


