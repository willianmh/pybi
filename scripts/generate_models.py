def create_init_files(schema_info: SchemaInfo) -> None:
    """Create ``__init__.py`` files for the versioned module structure.

    Two files are written:

    - **Version-level** (``{schema}/{version}/__init__.py``): re-exports
      everything from ``model.py``.
    - **Schema-level** (``{schema}/__init__.py``): re-exports from the
      version directory.  For ``semanticQuery``, also re-exports from
      ``expressions``.

    Note:
        When multiple versions of the same schema are generated, the
        schema-level ``__init__.py`` is overwritten each time, so only the
        **last version processed** ends up re-exported (last-version-wins).
    """
    version_init = schema_info.output_dir / "__init__.py"
    version_init.write_text(
        f'"""Generated models for {schema_info.name} version {schema_info.version}."""\n'
        f"from .model import *\n",
        encoding="utf-8",
    )

    schema_init = OUTPUT_ROOT / schema_info.module_name / "__init__.py"

    # Special handling for semanticQuery: also export hand-crafted expressions
    if schema_info.name == "semanticQuery":
        schema_init.write_text(
            f'"""SemanticQuery models package.\n'
            f"\n"
            f"This package provides Pydantic V2 models for Power BI semantic query structures,\n"
            f"including the hand-crafted QueryExpressionContainer that handles ~47 expression types.\n"
            f'"""\n'
            f"\n"
            f"# Export the hand-crafted expression container (always available)\n"
            f"from .expressions import *  # noqa: F401, F403\n"
            f"\n"
            f"# Export generated models\n"
            f"from .{schema_info.version_dir}.model import *  # noqa: F401, F403\n",
            encoding="utf-8",
        )
    else:
        schema_init.write_text(
            f'"""Models for {schema_info.name} - latest version: {schema_info.version}."""\n'
            f"from .{schema_info.version_dir}.model import *\n",
            encoding="utf-8",
        )


