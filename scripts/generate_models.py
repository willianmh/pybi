MAX_RETRIES = 3


def run_codegen(schema_info: SchemaInfo) -> bool:
    """Shell out to ``datamodel-codegen`` for a single schema file.

    Creates the output directory if needed, then runs the command with
    ``CODEGEN_BASE_FLAGS``.  On failure the command is retried up to
    ``MAX_RETRIES`` times with exponential back-off (``attempt * 2`` seconds).

    Side effects:
        - Creates ``schema_info.output_dir`` on disk.
        - Writes ``schema_info.output_file`` on success.

    Args:
        schema_info: Schema to generate.

    Returns:
        ``True`` if generation succeeded, ``False`` otherwise.

    Note:
        ``ModuleNotFoundError`` and ``ImportError`` are currently classified as
        "transient" and retried, but in practice these are deterministic
        failures that will not resolve on retry.
    """
    import time

    schema_info.output_dir.mkdir(parents=True, exist_ok=True)

    cmd = [
        "datamodel-codegen",
        "--input",
        str(schema_info.abs_path),
        *CODEGEN_BASE_FLAGS,
        "--output",
        str(schema_info.output_file),
    ]

    log.info("Running: %s", " ".join(cmd))

    for attempt in range(1, MAX_RETRIES + 1):
        try:
            result = subprocess.run(
                cmd,
                capture_output=True,
                text=True,
                check=False,
                timeout=120,
            )
            if result.returncode == 0:
                if result.stderr:
                    # Filter out the FutureWarning about formatters
                    important_warnings = [
                        line
                        for line in result.stderr.strip().split("\n")
                        if line.strip()
                        and "FutureWarning" not in line
                        and "code_formatter" not in line
                        and "datamodel_code_generator" not in line
                    ]
                    if important_warnings:
                        log.warning(
                            "datamodel-codegen warnings for %s:\n%s",
                            schema_info.key,
                            "\n".join(important_warnings),
                        )
                return True

            # Check if it's a transient error worth retrying
            stderr = result.stderr or ""
            is_transient = any(
                msg in stderr
                for msg in ("ModuleNotFoundError", "ImportError", "PermissionError")
            )

            if is_transient and attempt < MAX_RETRIES:
                log.warning(
                    "  Transient error on attempt %d/%d for %s, retrying in %ds...",
                    attempt,
                    MAX_RETRIES,
                    schema_info.key,
                    attempt * 2,
                )
                time.sleep(attempt * 2)
                continue

            log.error("datamodel-codegen failed for %s:\n%s", schema_info.key, stderr)
            return False

        except subprocess.TimeoutExpired:
            if attempt < MAX_RETRIES:
                log.warning(
                    "  Timeout on attempt %d/%d, retrying...", attempt, MAX_RETRIES
                )
                time.sleep(attempt * 2)
                continue
            log.error(
                "datamodel-codegen timed out for %s after %d attempts",
                schema_info.key,
                MAX_RETRIES,
            )
            return False
        except FileNotFoundError:
            log.error(
                "datamodel-codegen not found. Install with: pip install datamodel-code-generator"
            )
            return False

    return False


