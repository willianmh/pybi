# Regex that matches: <field_name>: <type> | None= Field(<non-None-default>,
# (detecting non-None primitive/string defaults for Optional fields)
_OPTIONAL_FIELD_BAD_DEFAULT = re.compile(
    r"(\b\w+: [^\n]+\|\s*None\s*=\s*Field\()"  # field_name: SomeType | None= Field(
    r"\s*(?!None\b)(?!\.\.\.\b)"  # not already None / required sentinel
    r"([^,\n]+)"  # existing default token
    r"\s*,",
    re.MULTILINE,
)

# Repair pattern for malformed output like Field(None, False, description=...)
_FIELD_NONE_DOUBLE_POSITIONAL = re.compile(
    r"Field\(None,\s*([^)]*?),\s*description=",
    re.DOTALL,
)


def _fix_optional_field_defaults(source: str) -> str:
    """Replace non-None primitive defaults on ``| None`` fields with ``None``.

    ``datamodel-codegen`` copies JSON Schema ``default`` values verbatim into
    ``Field(default, ...)``.  For Python models that use ``exclude_none=True``
    during serialisation, a non-None default causes the field to always appear
    in the serialised output even when the input data omitted it.

    After the main replacement, a defensive cleanup pass removes double-
    positional arguments of the form ``Field(None, <positional>, description=…)``
    that can be left behind by earlier transforms.

    Args:
        source: Complete Python source text of a generated model file.

    Returns:
        The source with all non-None defaults on Optional fields replaced by
        ``None``.  The number of replacements is logged at INFO level.

    Examples fixed::

        isToggled: bool | None= Field(False, ...)  →  Field(None, ...)
        highlightMatching: HM | None= Field(0, ...)  →  Field(None, ...)
        hierarchyMatching: HM | None= Field('long…', ...)  →  Field(None, ...)
    """
    count = [0]

    def _replace(match: re.Match) -> str:
        count[0] += 1
        return match.group(1) + "None,"

    result = _OPTIONAL_FIELD_BAD_DEFAULT.sub(_replace, source)

    # Defensive cleanup: if an older transform produced `Field(None, X, description=...)`
    # and X is positional (not keyword arg), drop X.
    def _cleanup_double_positional(match: re.Match) -> str:
        inner = match.group(1)
        if "=" in inner:
            return match.group(0)
        return "Field(None, description="

    result = _FIELD_NONE_DOUBLE_POSITIONAL.sub(_cleanup_double_positional, result)

    if count[0]:
        log.info("  Fixed %d non-None Optional field default(s)", count[0])
    return result


def _replace_constr_with_annotated(source: str) -> str:
    """Replace ``constr(...)`` with ``Annotated[str, StringConstraints(...)]``.

    ``datamodel-codegen`` emits Pydantic V1-style ``constr(pattern=..., max_length=...)``
    calls.  This function rewrites them to the modern Pydantic V2 form using
    ``Annotated`` and ``StringConstraints``, and adjusts the import block
    accordingly.

    Uses parenthesis counting instead of a regex to correctly handle pattern
    strings that contain ``)`` characters (e.g. ``r'^(a|b)$'``).
    """
    if "constr(" not in source:
        return source

    result: list[str] = []
    i = 0
    changed = False
    while i < len(source):
        if source[i : i + 7] == "constr(":
            start = i + 7  # position after the opening (
            depth = 1
            j = start
            while j < len(source) and depth > 0:
                if source[j] == "(":
                    depth += 1
                elif source[j] == ")":
                    depth -= 1
                j += 1
            args = source[start : j - 1]
            result.append(f"Annotated[str, StringConstraints({args})]")
            i = j
            changed = True
        else:
            result.append(source[i])
            i += 1

    new_source = "".join(result) if changed else source

    if new_source != source:
        # Remove constr from pydantic imports if present
        new_source = re.sub(
            r"^(from pydantic import .*)\bconstr,?\s*",
            lambda m: m.group(1),
            new_source,
            flags=re.MULTILINE,
        )
        # Clean up trailing comma + whitespace before closing or end of line
        new_source = re.sub(
            r"(from pydantic import [^)\n]*?),\s*$",
            r"\1",
            new_source,
            flags=re.MULTILINE,
        )

        # Add Annotated to existing typing import, or create one
        typing_import = re.search(
            r"^from typing import (.+)$", new_source, re.MULTILINE
        )
        if typing_import:
            if "Annotated" not in typing_import.group(1):
                new_source = new_source.replace(
                    typing_import.group(0),
                    typing_import.group(0).rstrip() + ", Annotated",
                )
        else:
            new_source = _insert_imports(new_source, ["from typing import Annotated"])

        # Add StringConstraints to existing pydantic import, or create one
        pydantic_import = re.search(
            r"^from pydantic import (.+)$", new_source, re.MULTILINE
        )
        if pydantic_import:
            if "StringConstraints" not in pydantic_import.group(1):
                new_source = new_source.replace(
                    pydantic_import.group(0),
                    pydantic_import.group(0).rstrip() + ", StringConstraints",
                )
        else:
            new_source = _insert_imports(
                new_source, ["from pydantic import StringConstraints"]
            )

        count = source.count("constr(")
        log.info(
            "  Replaced %d constr() call(s) with Annotated[str, StringConstraints(...)]",
            count,
        )

    return new_source


def _apply_post_generation_fixes(source: str, schema_info: "SchemaInfo") -> str:
    """Apply schema-specific field type corrections from ``POST_GENERATION_FIELD_FIXES``.

    These fixes address known naming collisions and forward-compatibility issues
    that the generic deduplication pipeline cannot resolve automatically (e.g.,
    a class-registry entry mapping ``SchemaEmbedded`` to the wrong schema).

    Each fix is a simple substring replacement.  If the expected fragment is not
    found in the source, a warning is logged: this typically means the upstream
    schema has changed and the fix table needs updating.

    Extra imports required by the replacement types are deduplicated against
    existing imports and inserted via :func:`_insert_imports`.

    Args:
        source: Post-processed Python source text.
        schema_info: The schema being fixed (used to look up its key in the
            ``POST_GENERATION_FIELD_FIXES`` table).

    Returns:
        The source with all applicable fixes applied.
    """
    fixes = POST_GENERATION_FIELD_FIXES.get(schema_info.key, [])
    if not fixes:
        return source

    extra_imports: list[str] = []
    for cls_name, old_fragment, new_fragment, imports in fixes:
        if old_fragment in source:
            source = source.replace(old_fragment, new_fragment, 1)
            extra_imports.extend(imports)
            log.info("  Applied field fix for %s", cls_name)
        else:
            log.warning(
                "  Field fix for %s not applied (fragment not found in source). "
                "Schema may have changed.",
                cls_name,
            )

    if extra_imports:
        # Filter out imports already present to avoid duplicates
        new_imports = [imp for imp in extra_imports if imp not in source]
        if new_imports:
            source = _insert_imports(source, new_imports)

        # Remove local class definitions that are now shadowed by imports
        for imp in extra_imports:
            m = re.match(r"from\s+\S+\s+import\s+(.+)", imp)
            if m:
                for name in m.group(1).split(","):
                    name = name.strip()
                    if name and name.isidentifier():
                        block = find_class_block(source, name)
                        if block:
                            start, end = block
                            source = source[:start] + source[end:]
                            log.info("  Removed shadowed class '%s'", name)

    return source


