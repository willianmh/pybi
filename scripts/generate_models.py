def remove_handcrafted_classes(source: str, schema_info: SchemaInfo) -> str:
    """Remove hand-crafted classes and their variants from generated source.

    For the ``semanticQuery`` schema, a curated set of classes (listed in
    ``HANDCRAFTED_CLASSES``) has hand-crafted implementations in
    ``expressions.py``.  This function:

    1. Removes the auto-generated class definition for each hand-crafted class.
    2. Removes all ``QueryExpressionContainer`` numbered variants
       (``QueryExpressionContainer1``, ``QueryExpressionContainer2``, etc.).
    3. Replaces references to numbered variants with the base class name.
    4. Cleans up resulting duplicate union members, list items, and
       ``model_rebuild()`` calls.
    5. Adds ``HANDCRAFTED_IMPORT`` (wildcard import) for ``semanticQuery``
       schemas only.

    Args:
        source: Generated Python source text.
        schema_info: The schema being processed (used to decide whether to
            add the hand-crafted import).

    Returns:
        The source with hand-crafted class definitions removed.
    """
    class_names = extract_class_names(source)
    classes_to_remove: list[str] = []

    for cls_name in class_names:
        # Check if it's a hand-crafted class
        if cls_name in HANDCRAFTED_CLASSES:
            classes_to_remove.append(cls_name)
        # Check if it's a QueryExpressionContainer numbered variant
        elif _QUERY_EXPR_CONTAINER_VARIANT.match(cls_name):
            classes_to_remove.append(cls_name)

    if not classes_to_remove:
        return source

    log.info("  Removing %d hand-crafted/variant classes", len(classes_to_remove))

    # Remove each class definition
    for cls_name in classes_to_remove:
        block = find_class_block(source, cls_name)
        if block:
            start, end = block
            source = source[:start] + source[end:]

    # Replace all references to numbered variants with QueryExpressionContainer
    for cls_name in classes_to_remove:
        if _QUERY_EXPR_CONTAINER_VARIANT.match(cls_name):
            source = re.sub(
                rf"\b{re.escape(cls_name)}\b",
                "QueryExpressionContainer",
                source,
            )

    # Clean up: remove duplicate union members
    source = _deduplicate_union_members(source)
    source = _deduplicate_list_items(source)
    source = _deduplicate_rebuild_calls(source)

    # Add explicit import for hand-crafted classes (only for semanticQuery schema)
    if schema_info.name == "semanticQuery":
        handcrafted_names = sorted(
            cls for cls in classes_to_remove if cls in HANDCRAFTED_CLASSES
        )
        if handcrafted_names:
            classes_str = ", ".join(handcrafted_names)
            source = _insert_imports(
                source, [f"from ..expressions import {classes_str}"]
            )

    # Remove any resulting blank line clusters
    source = re.sub(r"\n{4,}", "\n\n\n", source)

    return source


def pre_register_handcrafted_classes(registry: ClassRegistry) -> None:
    """Pre-register hand-crafted classes so downstream schemas import them.

    All classes in ``HANDCRAFTED_CLASSES`` are registered under the
    ``semanticQuery/1.3.0`` schema key with a sentinel signature
    (``"__handcrafted__"``).  This ensures that when any downstream schema
    generates the same class, :meth:`ClassRegistry.can_substitute` returns
    ``True`` and the duplicate is replaced with an import.

    Note:
        The schema key ``"semanticQuery/1.3.0"`` is hardcoded because the
        hand-crafted ``expressions.py`` module lives alongside the
        1.3.0 generated models and is shared across all versions.
    """
    # Register all hand-crafted classes as belonging to semanticQuery
    import_path = "semanticquery.expressions"
    schema_key = "semanticQuery/1.3.0"

    for cls_name in HANDCRAFTED_CLASSES:
        registry.register(
            cls_name,
            schema_key,
            import_path,
            signature="__handcrafted__",
        )

    log.info("  Pre-registered %d hand-crafted classes", len(HANDCRAFTED_CLASSES))


